/** Today's day number in Tehran, whatever the device's time zone is. */
export function tehranToday(now: Date = new Date()): number {
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Tehran', year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(now);
  const get = (type: string) => Number(parts.find((p) => p.type === type)?.value);
  return g2d(get('year'), get('month'), get('day'));
}
